#!/usr/bin/env python3
"""Apply the measured four-V100 profile to a setup-generated config; never overwrite."""
import argparse
import copy
import json
import os
import pathlib
import re
import secrets

ROOT = pathlib.Path(__file__).resolve().parents[1]

def remove_arg(args, flag, takes_value=True):
    while flag in args:
        i = args.index(flag)
        count = 2 if takes_value and i + 1 < len(args) and not args[i + 1].startswith('--') else 1
        del args[i:i + count]

def configure(base, gpus, aux_cpus=None):
    if len(gpus) != 4 or len(set(gpus)) != 4:
        raise ValueError('This measured profile requires four distinct GPU identifiers')
    if any(not re.fullmatch(r'\d+|GPU-[A-Fa-f0-9-]+', str(g)) for g in gpus):
        raise ValueError('GPU identifiers must be numeric indices or GPU UUIDs')
    if not isinstance(base.get('args'), list) or not base.get('exe'):
        raise ValueError('Use a model configuration generated by Strata setup')
    if aux_cpus is not None and not re.fullmatch(r'\d+(?:-\d+)?(?:,\d+(?:-\d+)?)*', aux_cpus):
        raise ValueError('Invalid auxiliary CPU list')
    c = copy.deepcopy(base)
    p = json.loads((ROOT / 'profiles/256k.json').read_text())
    args = c['args']
    for flag in p['removed_arguments']:
        remove_arg(args, flag)
    for flag, value in p['arguments'].items():
        remove_arg(args, flag)
        args.extend((flag, value))
    for flag in p['switches']:
        remove_arg(args, flag, takes_value=False)
        args.append(flag)
    c.pop('parallel', None)
    env = c.setdefault('env', {})
    env.pop('STRATA_PIPED_CONCURRENT', None)
    env.update(p['environment'])
    env['CUDA_VISIBLE_DEVICES'] = ','.join(map(str, gpus))
    if aux_cpus is not None:
        env['STRATA_AUX_CPUS'] = aux_cpus
    c['gpu'] = [int(g) if str(g).isdigit() else g for g in gpus]
    c['gpus_asked'] = copy.deepcopy(c['gpu'])
    c['layer_split'] = '14,26,38'
    c['host'] = '127.0.0.1'
    c['fit_max_tokens'] = True
    if not c.get('api_key'):
        c['api_key'] = secrets.token_urlsafe(32)
    return c

def write_new(path, config):
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, 'w') as f:
        json.dump(config, f, ensure_ascii=False, indent=2)
        f.write('\n')

def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--base', type=pathlib.Path, required=True)
    ap.add_argument('--output', type=pathlib.Path, required=True)
    ap.add_argument('--gpus', required=True, help='Four indices or GPU UUIDs in stage order')
    ap.add_argument('--aux-cpus', help='Optional topology-specific logical CPU list; reference used 25-47')
    a = ap.parse_args()
    c = configure(json.loads(a.base.read_text()), a.gpus.split(','), a.aux_cpus)
    write_new(a.output, c)
    print('Created a separate 256K single-sequence configuration (mode 0600).')
    print('API key retained/generated without printing it. No service, power cap or hugepage setting was changed.')

if __name__ == '__main__':
    main()
